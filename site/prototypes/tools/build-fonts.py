#!/usr/bin/env python3
"""Build the self-hosted font subsets for the homepage prototype.

The page's copy is fixed, so each font is cut down to the characters the page actually uses.
Run this again whenever the text of the pages listed in PAGES changes; a character that is
missing from a subset silently falls back to a system font.

    pip install fonttools brotli
    python3 site/prototypes/tools/build-fonts.py

Source fonts are fetched from the google/fonts repository into a cache directory (not committed).
Outputs go to site/prototypes/assets/fonts/: the .woff2 files, fonts.css and each family's OFL.txt.
"""

from __future__ import annotations

import argparse
import io
import re
import tempfile
import urllib.request
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "fonts"
SOURCE = "https://raw.githubusercontent.com/google/fonts/main/ofl"

# Files whose text decides which characters the subsets must contain.
PAGES = ["b-sky.html", "assets/proto.js"]

# Punctuation, symbols and arrows the pages use outside the Latin-1 block.
EXTRA = "‐‑–—―‘’“”•…′″‹›€™←↑→↓↖↗↘↙−✓✔◂·"
CJK = re.compile(r"[　-〿㐀-鿿＀-￯]")

# family, output file, source path, axis limits, style, weight descriptor, which characters
FACES = [
    ("Schibsted Grotesk", "schibsted-grotesk.woff2", "schibstedgrotesk/SchibstedGrotesk[wght].ttf",
     {"wght": (400, 600)}, "normal", "400 600", "latin"),
    ("Newsreader", "newsreader.woff2", "newsreader/Newsreader[opsz,wght].ttf",
     {"wght": (400, 500)}, "normal", "400 500", "latin"),
    ("Newsreader", "newsreader-italic.woff2", "newsreader/Newsreader-Italic[opsz,wght].ttf",
     {"wght": 400}, "italic", "400", "latin"),
    ("Fragment Mono", "fragment-mono.woff2", "fragmentmono/FragmentMono-Regular.ttf",
     {}, "normal", "400", "latin"),
    ("Noto Sans SC", "noto-sans-sc.woff2", "notosanssc/NotoSansSC[wght].ttf",
     {"wght": (400, 500)}, "normal", "400 500", "cjk"),
    ("Noto Serif SC", "noto-serif-sc.woff2", "notoserifsc/NotoSerifSC[wght].ttf",
     {"wght": 500}, "normal", "500", "cjk"),
]
LICENSES = ["schibstedgrotesk", "newsreader", "fragmentmono", "notosanssc", "notoserifsc"]


def fetch(path: str, cache: Path) -> Path:
    target = cache / path.replace("/", "-")
    if not target.exists():
        url = f"{SOURCE}/{urllib.request.quote(path)}"
        print(f"fetching {url}")
        urllib.request.urlretrieve(url, target)
    return target


def page_characters() -> tuple[set[int], set[int]]:
    text = "".join((ROOT / page).read_text(encoding="utf-8") for page in PAGES)
    cjk = {ord(ch) for ch in CJK.findall(text)}
    latin = set(range(0x20, 0x7F)) | set(range(0xA0, 0x100)) | {ord(ch) for ch in EXTRA}
    latin |= {ord(ch) for ch in text if ord(ch) > 0xFF and not CJK.match(ch) and not ch.isspace()}
    return latin, cjk


def ranges(codepoints: list[int]) -> str:
    """Compact unicode-range value for a sorted list of code points."""
    parts = []
    start = previous = codepoints[0]
    for cp in codepoints[1:] + [None]:
        if cp is not None and cp == previous + 1:
            previous = cp
            continue
        parts.append(f"U+{start:X}" if start == previous else f"U+{start:X}-{previous:X}")
        if cp is not None:
            start = previous = cp
    return ", ".join(parts)


def build(cache: Path) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    latin, cjk = page_characters()
    # arrows and CJK punctuation are served by the CJK faces when the Latin face lacks them
    wanted = {"latin": latin, "cjk": cjk | {ord(ch) for ch in EXTRA}}
    rules = [
        "/* Generated by tools/build-fonts.py. Do not edit: re-run the script after changing copy.",
        "   Each file is a subset holding only the characters the page uses. Licences: OFL-*.txt. */",
    ]
    for family, filename, source, limits, style, weight, kind in FACES:
        font = TTFont(fetch(source, cache))
        if limits and "fvar" in font:
            # Round-trip through a buffer: subsetting a freshly instanced font in memory trips on
            # its lazily loaded variation data.
            buffer = io.BytesIO()
            instancer.instantiateVariableFont(font, limits).save(buffer)
            buffer.seek(0)
            font = TTFont(buffer)
        options = subset.Options()
        options.flavor = "woff2"
        options.hinting = False
        options.desubroutinize = True
        options.layout_features = ["*"]
        options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
        options.notdef_outline = True
        subsetter = subset.Subsetter(options)
        subsetter.populate(unicodes=sorted(wanted[kind]))
        subsetter.subset(font)
        covered = sorted(set(font.getBestCmap()) & wanted[kind])
        target = OUT / filename
        subset.save_font(font, str(target), options)
        missing = len(wanted[kind]) - len(covered)
        print(f"{filename}: {len(covered)} characters, {target.stat().st_size / 1024:.0f} KB"
              + (f" ({missing} requested characters not in this font)" if missing else ""))
        rules += [
            "@font-face {",
            f'  font-family: "{family}";',
            f"  font-style: {style};",
            f"  font-weight: {weight};",
            "  font-display: swap;",
            f'  src: url("{filename}") format("woff2");',
            f"  unicode-range: {ranges(covered)};",
            "}",
        ]
    (OUT / "fonts.css").write_text("\n".join(rules) + "\n", encoding="utf-8")
    for family in LICENSES:
        licence = fetch(f"{family}/OFL.txt", cache)
        (OUT / f"OFL-{family}.txt").write_bytes(licence.read_bytes())
    print(f"wrote {OUT / 'fonts.css'}; format it with: pnpm exec prettier --write site/prototypes/assets/fonts")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--cache", type=Path, default=Path(tempfile.gettempdir()) / "kiteline-font-src",
                        help="directory for downloaded source fonts")
    arguments = parser.parse_args()
    arguments.cache.mkdir(parents=True, exist_ok=True)
    build(arguments.cache)
